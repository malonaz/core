// Package k8s generates the Kubernetes base of a MainManifest: the Deployment, Service,
// ServiceAccount and Ingresses of the binary, and the kustomization listing them. Nothing in it is
// environment specific; an overlay sets the image tag, replicas, env and hosts.
package k8s

import (
	"bytes"
	"fmt"
	"strconv"

	"gopkg.in/yaml.v3"

	onyxpb "github.com/malonaz/core/genproto/onyx/v1"
	"github.com/malonaz/core/tools/onyx/gen"
)

const (
	header    = "# Code generated by onyx. DO NOT EDIT.\n"
	nameLabel = "app.kubernetes.io/name"

	// Fixed by the health and prometheus opts of every binary.
	healthPort     = 4040
	prometheusPort = 13434
)

// Default ports of each listener, matching their opts' defaults.
const (
	defaultGRPCPort         = 9090
	defaultGatewayPort      = 8080
	defaultHTTPPort         = 8080
	defaultGRPCWebProxyPort = 8443
)

// listener is a TCP port the binary binds.
type listener struct {
	// The flag namespace, which also names its Service port and Ingress.
	namespace string
	port      int32
	internal  bool
	public    bool
}

// Generate renders the files of the binary, by filename. Image is what the Deployment runs.
func Generate(m *onyxpb.MainManifest, image string) (map[string][]byte, error) {
	listeners, env, err := resolve(m)
	if err != nil {
		return nil, err
	}

	name := m.GetName()
	labels := map[string]string{nameLabel: name}
	files := map[string][]byte{}
	filenames := []string{"serviceaccount.yaml", "deployment.yaml", "service.yaml"}

	add := func(filename string, objects ...any) error {
		data, err := encode(objects...)
		if err != nil {
			return fmt.Errorf("%s: %w", filename, err)
		}
		files[filename] = data
		return nil
	}

	if err := add("serviceaccount.yaml", &object{
		APIVersion: "v1",
		Kind:       "ServiceAccount",
		Metadata:   metadata{Name: name, Labels: labels},
	}); err != nil {
		return nil, err
	}

	ports := []containerPort{{ContainerPort: healthPort}, {ContainerPort: prometheusPort}}
	servicePorts := []servicePort{{Name: "metrics", Port: prometheusPort}}
	var ingresses []any
	for _, l := range listeners {
		if l.internal {
			continue
		}
		ports = append(ports, containerPort{ContainerPort: l.port})
		servicePorts = append(servicePorts, servicePort{Name: l.namespace, Port: l.port})
		if l.public {
			ingresses = append(ingresses, newIngress(name, labels, l))
		}
	}

	if err := add("deployment.yaml", &object{
		APIVersion: "apps/v1",
		Kind:       "Deployment",
		Metadata:   metadata{Name: name, Labels: labels},
		Spec: deploymentSpec{
			Selector: selector{MatchLabels: labels},
			Template: podTemplate{
				Metadata: metadata{
					Labels: labels,
					Annotations: map[string]string{
						"prometheus.io/scrape": "true",
						"prometheus.io/port":   strconv.Itoa(prometheusPort),
						"prometheus.io/path":   "/metrics",
					},
				},
				Spec: podSpec{
					ServiceAccountName: name,
					// Service links inject `{SERVICE}_PORT=tcp://...`, which collide with flags' env.
					EnableServiceLinks: false,
					Containers: []container{{
						Name:      name,
						Image:     image,
						Ports:     ports,
						Env:       env,
						Resources: newResources(m.GetResources()),
						// Liveness fails until the binary is ready, which setup can hold up for a while.
						StartupProbe:   &probe{HTTPGet: httpGet{Path: "/liveness", Port: healthPort}, PeriodSeconds: 5, FailureThreshold: 60},
						LivenessProbe:  &probe{HTTPGet: httpGet{Path: "/liveness", Port: healthPort}},
						ReadinessProbe: &probe{HTTPGet: httpGet{Path: "/readiness", Port: healthPort}},
					}},
				},
			},
		},
	}); err != nil {
		return nil, err
	}

	if err := add("service.yaml", &object{
		APIVersion: "v1",
		Kind:       "Service",
		Metadata:   metadata{Name: name, Labels: labels},
		Spec:       serviceSpec{Selector: labels, Ports: servicePorts},
	}); err != nil {
		return nil, err
	}

	if len(ingresses) > 0 {
		if err := add("ingress.yaml", ingresses...); err != nil {
			return nil, err
		}
		filenames = append(filenames, "ingress.yaml")
	}

	if err := add("kustomization.yaml", &kustomization{
		APIVersion: "kustomize.config.k8s.io/v1beta1",
		Kind:       "Kustomization",
		Resources:  filenames,
	}); err != nil {
		return nil, err
	}
	return files, nil
}

// resolve returns the listeners of the binary and the env binding each one.
func resolve(m *onyxpb.MainManifest) ([]*listener, []envVar, error) {
	var listeners []*listener
	var env []envVar
	setEnv := func(namespace, key, value string) {
		env = append(env, envVar{Name: gen.SnakeUpper(namespace) + "_" + key, Value: value})
	}
	listen := func(server *onyxpb.Server, namespace string, port, defaultPort int32) {
		if port == 0 {
			port = defaultPort
		}
		listeners = append(listeners, &listener{namespace: namespace, port: port, internal: server.GetInternal(), public: server.GetPublic()})
		setEnv(namespace, "PORT", strconv.Itoa(int(port)))
	}

	for _, server := range m.GetServers() {
		name := server.GetName()
		switch kind := server.GetKind().(type) {
		case *onyxpb.Server_Grpc_:
			namespace := name + "-grpc"
			if server.GetInternal() {
				setEnv(namespace, "SOCKET_PATH", "/tmp/"+name+".socket")
				setEnv(namespace, "DISABLE_TLS", "true")
			} else {
				listen(server, namespace, server.GetPort(), defaultGRPCPort)
			}
			if hasGateway(kind.Grpc) {
				listen(server, name+"-grpc-gateway", kind.Grpc.GetGatewayPort(), defaultGatewayPort)
			} else if kind.Grpc.GetGatewayPort() != 0 {
				return nil, nil, fmt.Errorf("server %s: gateway_port is set but no service sets gateway", name)
			}
		case *onyxpb.Server_Http_:
			listen(server, name+"-http", server.GetPort(), defaultHTTPPort)
		case *onyxpb.Server_GrpcWebProxy_:
			listen(server, name+"-grpcwebproxy", server.GetPort(), defaultGRPCWebProxyPort)
		case *onyxpb.Server_Processor_:
		default:
			return nil, nil, fmt.Errorf("server %s: unknown kind %T", name, kind)
		}
	}

	owners := map[int32]string{healthPort: "health", prometheusPort: "prometheus"}
	for _, l := range listeners {
		if owner, ok := owners[l.port]; ok {
			return nil, nil, fmt.Errorf("%s and %s both bind port %d; set port on one of them", owner, l.namespace, l.port)
		}
		owners[l.port] = l.namespace
		// Service port names are DNS labels.
		if len(l.namespace) > 63 {
			return nil, nil, fmt.Errorf("%s: longer than 63 characters, the limit of a Service port name", l.namespace)
		}
	}
	return listeners, env, nil
}

func newResources(r *onyxpb.Resources) *resources {
	quantities := func(q *onyxpb.Resources_Quantities) map[string]string {
		out := map[string]string{}
		if q.GetCpu() != "" {
			out["cpu"] = q.GetCpu()
		}
		if q.GetMemory() != "" {
			out["memory"] = q.GetMemory()
		}
		if len(out) == 0 {
			return nil
		}
		return out
	}
	requests, limits := quantities(r.GetRequests()), quantities(r.GetLimits())
	if requests == nil && limits == nil {
		return nil
	}
	return &resources{Requests: requests, Limits: limits}
}

func hasGateway(grpc *onyxpb.Server_Grpc) bool {
	for _, svc := range grpc.GetServices() {
		if svc.GetGateway() {
			return true
		}
	}
	return false
}

// newIngress routes everything to the listener. An overlay sets the host and controller annotations.
func newIngress(name string, labels map[string]string, l *listener) *object {
	return &object{
		APIVersion: "networking.k8s.io/v1",
		Kind:       "Ingress",
		Metadata:   metadata{Name: l.namespace, Labels: labels},
		Spec: ingressSpec{Rules: []ingressRule{{HTTP: httpIngress{Paths: []ingressPath{{
			Path:     "/",
			PathType: "Prefix",
			Backend:  ingressBackend{Service: ingressService{Name: name, Port: ingressServicePort{Name: l.namespace}}},
		}}}}}},
	}
}

func encode(objects ...any) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header)
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	for _, o := range objects {
		if err := encoder.Encode(o); err != nil {
			return nil, err
		}
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}
