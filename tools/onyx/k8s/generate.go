// Package k8s generates the Kubernetes base of a MainManifest, or of an ExternalManifest for a binary
// onyx does not generate: the Deployment, Service,
// ServiceAccount, NetworkPolicy, PodDisruptionBudget, Ingresses and ExternalSecret of the binary,
// and the kustomization listing them. Nothing in it is
// environment specific; an overlay sets the image tag, replicas, env and hosts.
package k8s

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"slices"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	networkingv1 "k8s.io/api/networking/v1"
	policyv1 "k8s.io/api/policy/v1"
	"k8s.io/apimachinery/pkg/api/resource"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/util/intstr"
	"k8s.io/utils/ptr"

	onyxpb "github.com/malonaz/core/genproto/onyx/v1"
	"github.com/malonaz/core/tools/onyx/manifest"
)

const (
	header = "# Code generated by onyx. DO NOT EDIT.\n"
	// The AWS Load Balancer Controller's annotation prefix.
	albAnnotation = "alb.ingress.kubernetes.io/"
	nameLabel     = "app.kubernetes.io/name"
	// The unprivileged appuser of the images.
	runAsUser = 10001
	// Linux's default ip_local_port_range, which outbound connections take ports from.
	ephemeralPortMin = 32768
	ephemeralPortMax = 60999
	// Kubernetes' default startup budget for the binary to become live.
	defaultStartupSeconds = 300
	probePeriodSeconds    = 5
)

// binary is what the base is generated from: an onyx binary's MainManifest, or an external
// binary's ExternalManifest.
type binary struct {
	name    string
	command []string
	// Every listener, including an onyx binary's sockets.
	listeners []*manifest.Listener
	// An onyx binary serves /liveness and /readiness on the health port and metrics on the
	// Prometheus port; an external binary is probed over grpc.health.v1 on grpcHealthPort, or else
	// over HTTP at httpHealthPath on httpHealthPort.
	grpcHealthPort  int32
	httpHealthPort  int32
	httpHealthPath  string
	resources       *onyxpb.Resources
	shutdownSeconds int32
	startupSeconds  int32
	writableDirs    []string
	// Synced by an ExternalSecret into the Secret named after the binary.
	secrets *onyxpb.Secrets
}

// Generate renders the files of an onyx binary, by filename. Image is what the Deployment runs.
func Generate(m *onyxpb.MainManifest, image string) (map[string][]byte, error) {
	listeners, err := manifest.Listeners(m.GetServers())
	if err != nil {
		return nil, err
	}
	return generate(&binary{
		name:            m.GetName(),
		listeners:       listeners,
		resources:       m.GetResources(),
		shutdownSeconds: m.GetShutdownSeconds(),
		startupSeconds:  m.GetStartupSeconds(),
		writableDirs:    m.GetWritableDirs(),
		secrets:         m.GetSecrets(),
	}, image)
}

// GenerateExternal renders the files of a binary onyx does not generate, by filename.
func GenerateExternal(m *onyxpb.ExternalManifest, image string) (map[string][]byte, error) {
	b := &binary{
		name:            m.GetName(),
		command:         m.GetCommand(),
		resources:       m.GetResources(),
		shutdownSeconds: m.GetShutdownSeconds(),
		startupSeconds:  m.GetStartupSeconds(),
		writableDirs:    m.GetWritableDirs(),
	}
	for _, l := range m.GetListeners() {
		b.listeners = append(b.listeners, &manifest.Listener{Namespace: m.GetName() + "-" + l.GetName(), Port: l.GetPort(), CustomPort: true, GRPC: l.GetGrpc(), Public: l.GetPublic()})
		if l.GetGrpc() && b.grpcHealthPort == 0 {
			b.grpcHealthPort = l.GetPort()
		}
		if l.GetHttpHealthPath() != "" && b.httpHealthPort == 0 {
			b.httpHealthPort, b.httpHealthPath = l.GetPort(), l.GetHttpHealthPath()
		}
	}
	return generate(b, image)
}

func generate(b *binary, image string) (map[string][]byte, error) {
	onyxBinary := b.grpcHealthPort == 0 && b.httpHealthPort == 0
	// Env could tell them apart, but nothing in the base sets it.
	portToOwner := map[int32]string{}
	if onyxBinary {
		portToOwner = map[int32]string{manifest.HealthPort: "health", manifest.PrometheusPort: "prometheus"}
	}
	for _, l := range b.listeners {
		if l.SocketPath == "" {
			if owner, ok := portToOwner[l.Port]; ok {
				return nil, fmt.Errorf("%s and %s both bind port %d; set port on one of them", owner, l.Namespace, l.Port)
			}
			portToOwner[l.Port] = l.Namespace
		}
	}

	name := b.name
	labels := map[string]string{nameLabel: name}
	files := map[string][]byte{}
	filenames := []string{"serviceaccount.yaml", "deployment.yaml", "service.yaml", "networkpolicy.yaml", "pdb.yaml"}

	add := func(filename string, objects ...any) error {
		data, err := encode(objects...)
		if err != nil {
			return fmt.Errorf("%s: %w", filename, err)
		}
		files[filename] = data
		return nil
	}
	meta := metav1.ObjectMeta{Name: name, Labels: labels}

	if err := add("serviceaccount.yaml", &corev1.ServiceAccount{
		TypeMeta:   metav1.TypeMeta{APIVersion: "v1", Kind: "ServiceAccount"},
		ObjectMeta: meta,
		// The binary never calls the Kubernetes API; IRSA projects its own token.
		AutomountServiceAccountToken: ptr.To(false),
	}); err != nil {
		return nil, err
	}

	var ports []corev1.ContainerPort
	var servicePorts []corev1.ServicePort
	var policyPorts []networkingv1.NetworkPolicyPort
	var annotations map[string]string
	var handler corev1.ProbeHandler
	readinessHandler := &handler
	if onyxBinary {
		ports = []corev1.ContainerPort{
			{Name: "health", ContainerPort: manifest.HealthPort},
			{Name: "metrics", ContainerPort: manifest.PrometheusPort},
		}
		servicePorts = []corev1.ServicePort{{Name: "metrics", Port: manifest.PrometheusPort, TargetPort: intstr.FromInt32(manifest.PrometheusPort)}}
		// The kubelet probes health and Prometheus scrapes metrics; nothing else reaches an unexposed port.
		policyPorts = []networkingv1.NetworkPolicyPort{newPolicyPort(manifest.HealthPort), newPolicyPort(manifest.PrometheusPort)}
		annotations = map[string]string{
			"prometheus.io/scrape": "true",
			"prometheus.io/port":   strconv.Itoa(manifest.PrometheusPort),
			"prometheus.io/path":   "/metrics",
		}
		handler = corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: "/liveness", Port: intstr.FromString("health")}}
		readinessHandler = &corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: "/readiness", Port: intstr.FromString("health")}}
	} else if b.grpcHealthPort == 0 {
		handler = corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: b.httpHealthPath, Port: intstr.FromInt32(b.httpHealthPort)}}
	} else {
		handler = corev1.ProbeHandler{GRPC: &corev1.GRPCAction{Port: b.grpcHealthPort}}
	}
	// Liveness fails until the binary is ready, which setup can hold up for a while.
	startupSeconds := b.startupSeconds
	if startupSeconds == 0 {
		startupSeconds = defaultStartupSeconds
	}
	startupProbe := &corev1.Probe{
		ProbeHandler:     handler,
		PeriodSeconds:    probePeriodSeconds,
		FailureThreshold: (startupSeconds + probePeriodSeconds - 1) / probePeriodSeconds,
	}

	var ingresses []any
	for _, l := range b.listeners {
		if l.SocketPath != "" || l.Internal {
			continue
		}
		// Service port names are DNS labels.
		if len(l.Namespace) > 63 {
			return nil, fmt.Errorf("%s: longer than 63 characters, the limit of a Service port name", l.Namespace)
		}
		ports = append(ports, corev1.ContainerPort{ContainerPort: l.Port})
		port := corev1.ServicePort{Name: l.Namespace, Port: l.Port, TargetPort: intstr.FromInt32(l.Port)}
		if l.GRPC {
			port.AppProtocol = ptr.To("grpc")
		}
		servicePorts = append(servicePorts, port)
		policyPorts = append(policyPorts, newPolicyPort(l.Port))
		if l.Public {
			ingresses = append(ingresses, newIngress(name, labels, l, b))
		}
	}

	// The root filesystem is read-only: /tmp holds sockets and temp files, and each writable dir gets
	// an emptyDir of its own.
	emptyDir := corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}
	volumes := []corev1.Volume{{Name: "tmp", VolumeSource: emptyDir}}
	volumeMounts := []corev1.VolumeMount{{Name: "tmp", MountPath: "/tmp"}}
	for _, dir := range b.writableDirs {
		if dir == "/tmp" {
			return nil, fmt.Errorf("writable dir /tmp: always mounted")
		}
		volumeName := strings.ReplaceAll(strings.Trim(strings.ReplaceAll(dir, ".", "-"), "/"), "/", "-")
		if len(volumeName) > 63 {
			return nil, fmt.Errorf("writable dir %s: longer than 63 characters as a volume name", dir)
		}
		volumes = append(volumes, corev1.Volume{Name: volumeName, VolumeSource: emptyDir})
		volumeMounts = append(volumeMounts, corev1.VolumeMount{Name: volumeName, MountPath: dir})
	}

	securityContext := &corev1.PodSecurityContext{
		RunAsNonRoot:   ptr.To(true),
		RunAsUser:      ptr.To[int64](runAsUser),
		SeccompProfile: &corev1.SeccompProfile{Type: corev1.SeccompProfileTypeRuntimeDefault},
	}
	// A listener in the ephemeral range can lose its port to an outbound connection made before it
	// binds; reserving it keeps the kernel from handing it out.
	if reserved := reservedPorts(b.listeners); reserved != "" {
		securityContext.Sysctls = []corev1.Sysctl{{Name: "net.ipv4.ip_local_reserved_ports", Value: reserved}}
	}

	resources, err := newResources(b.resources)
	if err != nil {
		return nil, err
	}
	// The Secret named after the binary: always referenced, so an overlay appends to envFrom rather
	// than replacing it, and required only when an ExternalSecret syncs it.
	secretEnv := &corev1.SecretEnvSource{LocalObjectReference: corev1.LocalObjectReference{Name: name}}
	if b.secrets == nil {
		secretEnv.Optional = ptr.To(true)
	}
	var terminationGracePeriodSeconds *int64
	if b.shutdownSeconds != 0 {
		terminationGracePeriodSeconds = ptr.To(int64(b.shutdownSeconds))
	}
	if err := add("deployment.yaml", &appsv1.Deployment{
		TypeMeta:   metav1.TypeMeta{APIVersion: "apps/v1", Kind: "Deployment"},
		ObjectMeta: meta,
		Spec: appsv1.DeploymentSpec{
			Selector: &metav1.LabelSelector{MatchLabels: labels},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: labels, Annotations: annotations},
				Spec: corev1.PodSpec{
					ServiceAccountName:           name,
					AutomountServiceAccountToken: ptr.To(false),
					// Service links inject `{SERVICE}_PORT=tcp://...`, which collide with flags' env.
					EnableServiceLinks:            ptr.To(false),
					TerminationGracePeriodSeconds: terminationGracePeriodSeconds,
					SecurityContext:               securityContext,
					Volumes:                       volumes,
					Containers: []corev1.Container{{
						Name:         name,
						Image:        image,
						Command:      b.command,
						EnvFrom:      []corev1.EnvFromSource{{SecretRef: secretEnv}},
						Ports:        ports,
						VolumeMounts: volumeMounts,
						Resources:    resources,
						SecurityContext: &corev1.SecurityContext{
							AllowPrivilegeEscalation: ptr.To(false),
							ReadOnlyRootFilesystem:   ptr.To(true),
							Capabilities:             &corev1.Capabilities{Drop: []corev1.Capability{"ALL"}},
						},
						StartupProbe:   startupProbe,
						LivenessProbe:  &corev1.Probe{ProbeHandler: handler},
						ReadinessProbe: &corev1.Probe{ProbeHandler: *readinessHandler},
					}},
				},
			},
		},
	}); err != nil {
		return nil, err
	}

	if err := add("service.yaml", &corev1.Service{
		TypeMeta:   metav1.TypeMeta{APIVersion: "v1", Kind: "Service"},
		ObjectMeta: meta,
		Spec:       corev1.ServiceSpec{Selector: labels, Ports: servicePorts},
	}); err != nil {
		return nil, err
	}

	if err := add("networkpolicy.yaml", &networkingv1.NetworkPolicy{
		TypeMeta:   metav1.TypeMeta{APIVersion: "networking.k8s.io/v1", Kind: "NetworkPolicy"},
		ObjectMeta: meta,
		// Ingress only, from anywhere, to the exposed ports. Egress (databases, AWS, other services) is
		// environment specific, so an overlay restricts it.
		Spec: networkingv1.NetworkPolicySpec{
			PodSelector: metav1.LabelSelector{MatchLabels: labels},
			PolicyTypes: []networkingv1.PolicyType{networkingv1.PolicyTypeIngress},
			Ingress:     []networkingv1.NetworkPolicyIngressRule{{Ports: policyPorts}},
		},
	}); err != nil {
		return nil, err
	}

	// Node drains and upgrades take down one pod at a time.
	if err := add("pdb.yaml", &policyv1.PodDisruptionBudget{
		TypeMeta:   metav1.TypeMeta{APIVersion: "policy/v1", Kind: "PodDisruptionBudget"},
		ObjectMeta: meta,
		Spec: policyv1.PodDisruptionBudgetSpec{
			MaxUnavailable: ptr.To(intstr.FromInt32(1)),
			Selector:       &metav1.LabelSelector{MatchLabels: labels},
		},
	}); err != nil {
		return nil, err
	}

	if b.secrets != nil {
		var dataFrom []externalSecretDataFrom
		for _, blob := range b.secrets.GetBlobs() {
			dataFrom = append(dataFrom, externalSecretDataFrom{Extract: externalSecretKey{Key: blob}})
		}
		if err := add("externalsecret.yaml", &externalSecret{
			APIVersion: "external-secrets.io/v1",
			Kind:       "ExternalSecret",
			Metadata:   meta,
			Spec: externalSecretSpec{
				SecretStoreRef: secretStoreRef{Kind: "SecretStore", Name: b.secrets.GetStore()},
				DataFrom:       dataFrom,
			},
		}); err != nil {
			return nil, err
		}
		filenames = append(filenames, "externalsecret.yaml")
	}

	if len(ingresses) > 0 {
		if err := add("ingress.yaml", ingresses...); err != nil {
			return nil, err
		}
		filenames = append(filenames, "ingress.yaml")
	}

	if err := add("kustomization.yaml", &kustomization{
		APIVersion: "kustomize.config.k8s.io/v1beta1",
		Kind:       "Kustomization",
		Resources:  filenames,
	}); err != nil {
		return nil, err
	}
	return files, nil
}

// reservedPorts lists the TCP listener ports in the ephemeral range, consecutive ones as a range:
// `45322-45325,45330`.
func reservedPorts(listeners []*manifest.Listener) string {
	var ports []int32
	for _, l := range listeners {
		if l.SocketPath == "" && l.Port >= ephemeralPortMin && l.Port <= ephemeralPortMax {
			ports = append(ports, l.Port)
		}
	}
	slices.Sort(ports)
	ports = slices.Compact(ports)
	var ranges []string
	for i := 0; i < len(ports); {
		j := i
		for j+1 < len(ports) && ports[j+1] == ports[j]+1 {
			j++
		}
		if i == j {
			ranges = append(ranges, strconv.Itoa(int(ports[i])))
		} else {
			ranges = append(ranges, fmt.Sprintf("%d-%d", ports[i], ports[j]))
		}
		i = j + 1
	}
	return strings.Join(ranges, ",")
}

func newPolicyPort(port int32) networkingv1.NetworkPolicyPort {
	return networkingv1.NetworkPolicyPort{Protocol: ptr.To(corev1.ProtocolTCP), Port: ptr.To(intstr.FromInt32(port))}
}

func newResources(r *onyxpb.Resources) (corev1.ResourceRequirements, error) {
	quantities := func(field string, q *onyxpb.Resources_Quantities) (corev1.ResourceList, error) {
		list := corev1.ResourceList{}
		for resourceName, value := range map[corev1.ResourceName]string{corev1.ResourceCPU: q.GetCpu(), corev1.ResourceMemory: q.GetMemory()} {
			if value == "" {
				continue
			}
			quantity, err := resource.ParseQuantity(value)
			if err != nil {
				return nil, fmt.Errorf("resources.%s.%s: %w", field, resourceName, err)
			}
			list[resourceName] = quantity
		}
		if len(list) == 0 {
			return nil, nil
		}
		return list, nil
	}
	requests, err := quantities("requests", r.GetRequests())
	if err != nil {
		return corev1.ResourceRequirements{}, err
	}
	limits, err := quantities("limits", r.GetLimits())
	if err != nil {
		return corev1.ResourceRequirements{}, err
	}
	return corev1.ResourceRequirements{Requests: requests, Limits: limits}, nil
}

// newIngress routes everything to the listener. Its annotations are what the AWS Load Balancer
// Controller needs per listener, and other controllers ignore: the port it listens on, and how the
// listener's target group checks health. An overlay sets the class and the rest.
func newIngress(name string, labels map[string]string, l *manifest.Listener, b *binary) *networkingv1.Ingress {
	annotations := map[string]string{
		albAnnotation + "listen-ports": fmt.Sprintf(`[{"HTTPS": %d}]`, l.Port),
	}
	switch {
	case l.GRPC:
		// Every grpc server serves grpc.health.v1 on its own port.
		annotations[albAnnotation+"backend-protocol-version"] = "GRPC"
		annotations[albAnnotation+"healthcheck-port"] = "traffic-port"
		annotations[albAnnotation+"healthcheck-path"] = "/grpc.health.v1.Health/Check"
		annotations[albAnnotation+"success-codes"] = "0"
	case b.grpcHealthPort == 0 && b.httpHealthPort == 0:
		annotations[albAnnotation+"healthcheck-port"] = strconv.Itoa(manifest.HealthPort)
		annotations[albAnnotation+"healthcheck-path"] = "/readiness"
	case b.httpHealthPort != 0:
		annotations[albAnnotation+"healthcheck-port"] = strconv.Itoa(int(b.httpHealthPort))
		annotations[albAnnotation+"healthcheck-path"] = b.httpHealthPath
	}
	return &networkingv1.Ingress{
		TypeMeta:   metav1.TypeMeta{APIVersion: "networking.k8s.io/v1", Kind: "Ingress"},
		ObjectMeta: metav1.ObjectMeta{Name: l.Namespace, Labels: labels, Annotations: annotations},
		Spec: networkingv1.IngressSpec{Rules: []networkingv1.IngressRule{{
			IngressRuleValue: networkingv1.IngressRuleValue{HTTP: &networkingv1.HTTPIngressRuleValue{Paths: []networkingv1.HTTPIngressPath{{
				Path:     "/",
				PathType: ptr.To(networkingv1.PathTypePrefix),
				// By number: an Ingress names a port only up to 15 characters, and ours are flag namespaces.
				Backend: networkingv1.IngressBackend{Service: &networkingv1.IngressServiceBackend{
					Name: name,
					Port: networkingv1.ServiceBackendPort{Number: l.Port},
				}},
			}}}},
		}}},
	}
}

// externalSecret is the External Secrets Operator's ExternalSecret, whose Secret takes its name;
// the operator's own types would pull in the operator.
type externalSecret struct {
	APIVersion string             `json:"apiVersion"`
	Kind       string             `json:"kind"`
	Metadata   metav1.ObjectMeta  `json:"metadata"`
	Spec       externalSecretSpec `json:"spec"`
}

type externalSecretSpec struct {
	SecretStoreRef secretStoreRef           `json:"secretStoreRef"`
	DataFrom       []externalSecretDataFrom `json:"dataFrom"`
}

type secretStoreRef struct {
	Kind string `json:"kind"`
	Name string `json:"name"`
}

// externalSecretDataFrom sets every key of the blob.
type externalSecretDataFrom struct {
	Extract externalSecretKey `json:"extract"`
}

type externalSecretKey struct {
	Key string `json:"key"`
}

// kustomization lists the base's files; kustomize's own types would pull in kustomize.
type kustomization struct {
	APIVersion string   `json:"apiVersion"`
	Kind       string   `json:"kind"`
	Resources  []string `json:"resources"`
}

// encode writes the objects as one YAML stream, through their JSON form as the API server reads
// them. It drops the `status` a manifest never sets, and what the Go types emit for unset fields
// (`creationTimestamp: null`, `strategy: {}`): nulls, and empty objects other than an `emptyDir`.
func encode(objects ...any) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header)
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	for _, o := range objects {
		data, err := json.Marshal(o)
		if err != nil {
			return nil, err
		}
		var tree any
		if err := json.Unmarshal(data, &tree); err != nil {
			return nil, err
		}
		if object, ok := tree.(map[string]any); ok {
			delete(object, "status")
		}
		if err := encoder.Encode(prune(tree)); err != nil {
			return nil, err
		}
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

// prune drops nulls and empty objects (but an emptyDir's) under v, and writes whole numbers as
// integers rather than JSON's floats.
func prune(v any) any {
	switch v := v.(type) {
	case map[string]any:
		for key, child := range v {
			child = prune(child)
			if object, ok := child.(map[string]any); child == nil || (ok && len(object) == 0 && key != "emptyDir") {
				delete(v, key)
				continue
			}
			v[key] = child
		}
		return v
	case []any:
		for i, child := range v {
			v[i] = prune(child)
		}
		return v
	case float64:
		if v == math.Trunc(v) {
			return int64(v)
		}
		return v
	default:
		return v
	}
}
