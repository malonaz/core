// Package service generates the Service type of a ServiceManifest: its constructor over the declared
// dependencies, the generated servers it embeds and its Start.
package service

import (
	"fmt"
	"path"
	"strings"

	onyxpb "github.com/malonaz/core/genproto/onyx/v1"
	"github.com/malonaz/core/tools/onyx/gen"
	"github.com/malonaz/core/tools/onyx/manifest"
)

const (
	core   = "github.com/malonaz/core/go"
	header = "// Code generated by onyx. DO NOT EDIT."
)

// Generate renders the service file of the manifest.
func Generate(m *onyxpb.ServiceManifest, goImportPath string) ([]byte, error) {
	target, err := manifest.ParseLabel(m.GetTarget())
	if err != nil {
		return nil, err
	}
	f := gen.NewFile(path.Base(target.GoImportPath(goImportPath)), header)
	g := &generator{File: f, m: m, goImportPath: goImportPath}
	if err := g.generate(); err != nil {
		return nil, err
	}
	return f.Bytes()
}

type generator struct {
	*gen.File
	m            *onyxpb.ServiceManifest
	goImportPath string
}

// dependency is a constructor argument: its field on Service and its parameter to New.
type dependency struct {
	field string
	typ   string
	param string
}

func (g *generator) field(name string) string {
	if g.m.GetExportServiceFields() {
		return strings.Title(name)
	}
	return name
}

func (g *generator) dependencies() ([]dependency, error) {
	var deps []dependency
	for _, dep := range g.m.GetDependencies() {
		switch kind := dep.GetKind().(type) {
		case *onyxpb.Dependency_GrpcClient_:
			svc, err := g.grpcService(kind.GrpcClient)
			if err != nil {
				return nil, err
			}
			param := gen.Camel(svc.Name) + "Client"
			deps = append(deps, dependency{g.field(param), gen.PB(g.File, svc) + "." + svc.GoName + "Client", param})
		case *onyxpb.Dependency_PostgresDbClient_:
			param := kind.PostgresDbClient.GetName() + "PostgresStore"
			deps = append(deps, dependency{g.field(param), "*" + g.Qual(g.goPath(kind.PostgresDbClient.GetTarget()), "Store"), param})
		case *onyxpb.Dependency_PostgresClient_:
			param := kind.PostgresClient.GetName() + "PostgresClient"
			deps = append(deps, dependency{g.field(param), "*" + g.Qual(core+"/postgres", "Client"), param})
		case *onyxpb.Dependency_Service_:
			param := kind.Service.GetName() + "Service"
			deps = append(deps, dependency{g.field(param), "*" + g.Qual(g.goPath(kind.Service.GetTarget()), "Service"), param})
		case *onyxpb.Dependency_Nats_:
			deps = append(deps, dependency{g.field("natsClient"), "*" + g.Qual(core+"/nats", "Client"), "natsClient"})
		default:
			return nil, fmt.Errorf("unknown dependency kind %T", kind)
		}
	}
	return deps, nil
}

func (g *generator) goPath(label string) string {
	parsed, err := manifest.ParseLabel(label)
	if err != nil {
		return label
	}
	return parsed.GoImportPath(g.goImportPath)
}

func (g *generator) grpcService(client *onyxpb.Dependency_GrpcClient) (*manifest.GRPCService, error) {
	proto, err := manifest.ParseLabel(client.GetProto())
	if err != nil {
		return nil, err
	}
	return manifest.ResolveGRPCService(proto, client.GetService(), g.goImportPath)
}

func (g *generator) generate() error {
	ctx := g.Import("context")
	deps, err := g.dependencies()
	if err != nil {
		return err
	}

	// Long-running servers hand their operations to the scheduler.
	var schedulerClient string
	var longrunning bool
	for _, dep := range g.m.GetDependencies() {
		if client := dep.GetGrpcClient(); client != nil && client.GetService() == "scheduler-service" {
			schedulerClient = gen.Camel(client.GetService()) + "Client"
		}
	}
	for _, codegen := range g.m.GetCodegens() {
		if codegen.GetRpc().GetLongrunning() {
			longrunning = true
		}
	}
	if longrunning && schedulerClient == "" {
		return fmt.Errorf("a longrunning codegen requires a grpc_client dependency on scheduler-service")
	}

	if g.m.GetIncludeRuntime() {
		g.P("type Opts struct{}")
		g.P()
		g.P("type runtime struct{}")
		g.P()
		g.P("func newRuntime(opts *Opts) (*runtime, error) {")
		g.P("return &runtime{}, nil")
		g.P("}")
		g.P()
		g.P("func (s *Service) start(ctx ", ctx, ".Context) (func(), error) { return func() {}, nil }")
		g.P()
	}

	g.P("type Service struct {")
	g.P("*runtime")
	for _, codegen := range g.m.GetCodegens() {
		rpc := codegen.GetRpc()
		g.P("*", g.Qual(g.goPath(rpc.GetTarget()), gen.Pascal(rpc.GetName())+"Server"))
	}
	if longrunning {
		g.P("// Serves google.longrunning.Operations for the long-running methods above.")
		g.P("*", g.Qual(core+"/scheduler/longrunning", "Server"))
	}
	g.P("log *", g.Qual("log/slog", "Logger"))
	g.P(g.field("opts"), " *Opts")
	g.P(g.field("withServiceAccount"), " func(", ctx, ".Context) ", ctx, ".Context")
	for _, dep := range deps {
		g.P(dep.field, " ", dep.typ)
	}
	g.P("}")
	g.P()

	g.P("func (s *Service) WithLogger(logger *", g.Qual("log/slog", "Logger"), ") *Service {")
	g.P("s.log = logger")
	g.P("return s")
	g.P("}")
	g.P()

	g.P("func New(")
	g.P("opts *Opts,")
	for _, dep := range deps {
		g.P(dep.param, " ", dep.typ, ",")
	}
	g.P(") (*Service, error) {")
	g.P("runtime, err := newRuntime(opts)")
	g.P("if err != nil {")
	g.P("return nil, ", g.Qual("fmt", "Errorf"), `("instantiating runtime: %w", err)`)
	g.P("}")
	g.P("service := &Service{")
	g.P("runtime: runtime,")
	g.P("log: ", g.Qual("log/slog", "Default"), "(),")
	g.P(g.field("opts"), ": opts,")
	for _, dep := range deps {
		g.P(dep.field, ": ", dep.param, ",")
	}
	g.P("}")
	for _, codegen := range g.m.GetCodegens() {
		rpc := codegen.GetRpc()
		args := []string{gen.Camel(rpc.GetStore()) + "PostgresStore"}
		if rpc.GetNats() {
			args = append(args, "natsClient")
		}
		if rpc.GetLongrunning() {
			// The service itself is the runner: it implements Run{Method} for each long-running method.
			args = append(args, schedulerClient, "service")
		}
		server := gen.Pascal(rpc.GetName()) + "Server"
		g.P("service.", server, " = ", g.Qual(g.goPath(rpc.GetTarget()), "New"+server), "(", strings.Join(args, ", "), ")")
	}
	if longrunning {
		g.P("service.Server = ", g.Qual(core+"/scheduler/longrunning", "NewServer"), "(", schedulerClient, ", ", g.Qual("slices", "Concat"), "(")
		for _, codegen := range g.m.GetCodegens() {
			if rpc := codegen.GetRpc(); rpc.GetLongrunning() {
				g.P(g.Qual(g.goPath(rpc.GetTarget()), gen.Pascal(rpc.GetName())+"LongrunningMethods"), ",")
			}
		}
		g.P("))")
	}
	g.P("return service, nil")
	g.P("}")
	g.P()

	g.P("func (s *Service) Start(ctx ", ctx, ".Context, withServiceAccount func(", ctx, ".Context) ", ctx, ".Context) (func(), error) {")
	g.P("if withServiceAccount != nil {")
	g.P("s.", g.field("withServiceAccount"), " = withServiceAccount")
	g.P("ctx = withServiceAccount(ctx)")
	g.P("}")
	for _, codegen := range g.m.GetCodegens() {
		rpc := codegen.GetRpc()
		g.P("if err := s.", gen.Pascal(rpc.GetName()), "Server.Start(ctx); err != nil {")
		g.P("return nil, ", g.Qual("fmt", "Errorf"), `("starting `, rpc.GetName(), ` server: %w", err)`)
		g.P("}")
	}
	g.P("return s.start(ctx)")
	g.P("}")
	return nil
}
