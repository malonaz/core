package binary

import (
	"strings"

	onyxpb "github.com/malonaz/core/genproto/onyx/v1"
	"github.com/malonaz/core/tools/onyx/gen"
)

const (
	core   = "github.com/malonaz/core/go"
	header = "// Code generated by onyx. DO NOT EDIT."
)

// Generate renders the main package of the binary.
func Generate(b *Binary) ([]byte, error) {
	g := &generator{File: gen.NewFile("main", header), b: b}
	g.generate()
	return g.Bytes()
}

type generator struct {
	*gen.File
	b *Binary
}

// interceptor is how a Server.Grpc interceptor is configured and instantiated.
type interceptor struct {
	// Its own opts and constructor, for authentication interceptors.
	opts bool
	// Takes the context, for constructors that load remote configuration.
	ctx bool
	// The session manager method, for the injectors.
	method string
}

var interceptors = map[onyxpb.Interceptor]interceptor{
	onyxpb.Interceptor_INTERCEPTOR_SESSION_LOCAL_CONTEXT_INJECTOR:    {method: "LocalContextInjector"},
	onyxpb.Interceptor_INTERCEPTOR_SESSION_LOG_INJECTOR:              {method: "LogInjector"},
	onyxpb.Interceptor_INTERCEPTOR_SESSION_OUTGOING_CONTEXT_INJECTOR: {method: "OutgoingContextInjector"},
	onyxpb.Interceptor_INTERCEPTOR_EXTERNAL_API_KEY_AUTHENTICATION:   {opts: true},
	onyxpb.Interceptor_INTERCEPTOR_INTERNAL_SERVICE_AUTHENTICATION:   {opts: true},
	onyxpb.Interceptor_INTERCEPTOR_JWT_AUTHENTICATION:                {opts: true, ctx: true},
	onyxpb.Interceptor_INTERCEPTOR_PERMISSION_AUTHENTICATION:         {opts: true},
}

// interceptorName is the interceptor's Go name: `ExternalApiKeyAuthentication`.
func interceptorName(i onyxpb.Interceptor) string {
	return gen.Pascal(strings.ToLower(strings.TrimPrefix(i.String(), "INTERCEPTOR_")))
}

func (g *generator) sessionManager() bool {
	return len(g.b.Interceptors) > 0
}

func (g *generator) internalServiceAuthentication() bool {
	for _, i := range g.b.Interceptors {
		if i == onyxpb.Interceptor_INTERCEPTOR_INTERNAL_SERVICE_AUTHENTICATION {
			return true
		}
	}
	return false
}

// longrunning reports whether a service returns google.longrunning.Operation from some method.
func longrunning(s *Service) bool {
	for _, codegen := range s.GetCodegens() {
		if codegen.GetRpc().GetLongrunning() {
			return true
		}
	}
	return false
}

// Identifiers.
func serviceVar(s *Service) string        { return gen.Camel(s.GetName()) }
func serviceOpts(s *Service) string       { return "opts." + gen.Pascal(s.GetName()) }
func clientVar(c *GRPCClient) string      { return gen.Camel(c.Name) + "Client" }
func healthCheckVar(c *GRPCClient) string { return gen.Camel(c.Name) + "HealthCheck" }
func storeVar(s *Store) string            { return gen.Camel(s.Name) + "Store" }
func psqlVar(d *Database) string          { return gen.Camel(d.Name) + "PsqlClient" }
func componentVar(c *Component) string    { return gen.Camel(c.Name) + "Service" }
func serverVar(s *Server, kind string) string {
	return gen.Camel(s.GetName()) + kind
}
func serverOpts(s *Server, kind string) string { return "opts." + gen.Pascal(s.GetName()) + kind }

func (g *generator) grpcOptsField(name string) string {
	return "opts." + gen.Pascal(name) + "GRPC"
}

func (g *generator) generate() {
	ctx := g.Import("context")
	fmt_ := g.Import("fmt")

	for _, server := range g.b.Servers {
		if grpc := server.GetGrpc(); grpc.GetDescriptorSet() != "" {
			g.ImportBlank("embed")
			g.P("//go:embed ", grpc.GetDescriptorSet())
			g.P("var ", serverVar(server, "DescriptorSetBytes"), " []byte")
			g.P()
		}
	}

	g.opts()

	g.P("func main() {")
	g.P("ctx := ", ctx, ".Background()")
	g.P("if err := run(ctx); err != nil {")
	g.P(g.Qual("log/slog", "ErrorContext"), `(ctx, "running", "error", err)`)
	g.P(g.Qual("os", "Exit"), "(1)")
	g.P("}")
	g.P("}")
	g.P()

	g.P("func run(ctx ", ctx, ".Context) error {")
	g.P("if err := ", g.Qual(core+"/flags", "Parse"), "(&opts); err != nil {")
	g.P("return err")
	g.P("}")
	g.P("if err := ", g.Qual(core+"/logging", "Init"), "(opts.Logging); err != nil {")
	g.P("return err")
	g.P("}")
	if g.b.Setup {
		g.P("if err := setup(ctx); err != nil {")
		g.P("return ", fmt_, `.Errorf("setup: %w", err)`)
		g.P("}")
	}
	g.P()
	g.P("prometheusServer := ", g.Qual(core+"/prometheus", "NewServer"), "(opts.Prometheus)")
	g.P("go prometheusServer.Start(ctx)")
	g.P("defer prometheusServer.Stop(ctx)")
	g.P()
	if g.sessionManager() {
		g.P("sessionManager := ", g.Qual(core+"/authentication", "NewSessionManager"), "(opts.SessionManager)")
		g.P()
	}
	g.P("errChan := make(chan error, 1)")
	g.P("runServer := func(ctx ", ctx, ".Context, name string, serve func(", ctx, ".Context) error) {")
	g.P("go func() {")
	g.P("if err := serve(ctx); err != nil {")
	g.P("errChan <- ", fmt_, `.Errorf("serving %s: %w", name, err)`)
	g.P("}")
	g.P("}()")
	g.P("}")

	g.grpcClients()
	g.postgres()
	g.nats()
	g.components()
	g.interceptors()

	g.P()
	g.P("healthServer := ", g.Qual(core+"/health", "NewServer"), "(opts.Health, \"", g.b.Name, "\")")
	g.P("var gracefulStopFns []func() error")
	g.P("var stopFns []func() error")

	started := map[*Service]bool{}
	for _, server := range g.b.Servers {
		g.P()
		g.P("// ", server.GetName())
		for _, service := range server.Services {
			if !started[service] {
				started[service] = true
				g.service(service)
			}
		}
		switch server.GetKind().(type) {
		case *onyxpb.Server_Grpc_:
			g.grpcServer(server)
		case *onyxpb.Server_Http_:
			g.httpServer(server)
		case *onyxpb.Server_GrpcWebProxy_:
			g.grpcWebProxy(server)
		case *onyxpb.Server_Processor_:
			g.P("healthServer.RegisterService(\"", server.GetName(), "\", ", serviceVar(server.Services[0]), ".HealthCheck)")
		}
	}

	g.P()
	g.P("go healthServer.Serve(ctx)")
	g.P("gracefulStopFns = append(gracefulStopFns, func() error {")
	g.P("healthServer.Shutdown()")
	g.P("return nil")
	g.P("})")
	g.P("healthServer.MarkReady()")
	g.P("handleSignals(ctx, errChan, gracefulStopFns, stopFns)")
	g.P("return nil")
	g.P("}")
	g.P()

	g.handleSignals()
}

func (g *generator) opts() {
	grpc := g.Import(core + "/grpc")
	g.P("var opts struct {")
	g.P("Logging *", g.Qual(core+"/logging", "Opts"), " ", gen.Tag("Logging", "logging"))
	g.P("Health *", g.Qual(core+"/health", "Opts"), " ", gen.Tag("Health", "health"))
	g.P("Prometheus *", g.Qual(core+"/prometheus", "Opts"), " ", gen.Tag("Prometheus", "prometheus"))
	g.P("Certs *", g.Qual(core+"/certs", "Opts"), " ", gen.Tag("Certs", "certs"))

	if g.sessionManager() {
		g.P()
		g.P("SessionManager *", g.Qual(core+"/authentication", "SessionManagerOpts"), " ", gen.Tag("Session Manager", "session-manager"))
		for _, i := range g.b.Interceptors {
			if interceptors[i].opts {
				name := interceptorName(i)
				g.P(name, " *", g.Qual(core+"/authentication", name+"InterceptorOpts"), " ", gen.Tag(gen.Human(name), gen.Kebab(name)))
			}
		}
	}

	if len(g.b.Components) > 0 {
		g.P()
		for _, component := range g.b.Components {
			g.P(gen.Pascal(component.Name), "Service *", g.Qual(component.Target.GoImportPath(g.b.GoImportPath), "Opts"), " ", gen.Tag(gen.Human(component.Name)+" Service", gen.Kebab(component.Name)+"-service"))
		}
	}

	if len(g.b.Databases) > 0 {
		g.P()
		for _, database := range g.b.Databases {
			g.P(gen.Pascal(database.Name), "Postgres *", g.Qual(core+"/postgres", "Opts"), " ", gen.Tag(gen.Human(database.Name)+" Postgres", gen.Kebab(database.Name)+"-postgres"))
		}
	}

	if g.b.Nats {
		g.P()
		g.P("Nats *", g.Qual(core+"/nats", "Opts"), " ", gen.Tag("Nats", "nats"))
	}

	var remote []*GRPCClient
	for _, client := range g.b.GRPCClients {
		if client.Server == nil {
			remote = append(remote, client)
		}
	}
	if len(remote) > 0 {
		g.P()
		g.P("// gRPC clients of services outside this binary.")
		for _, client := range remote {
			g.P(client.GoName, "GRPC *", grpc, ".ClientOpts ", gen.Tag(gen.Human(client.Name)+" GRPC (Client)", gen.Kebab(client.Name)+"-grpc"))
		}
	}

	g.P()
	g.P("// Servers. In-process clients of a gRPC server dial it through these same opts.")
	for _, server := range g.b.Servers {
		name := gen.Pascal(server.GetName())
		switch kind := server.GetKind().(type) {
		case *onyxpb.Server_Grpc_:
			g.P(name, "GRPC *", grpc, ".ServerOpts ", gen.Tag(name+" GRPC (Server)", server.GetName()+"-grpc"))
			for _, svc := range kind.Grpc.GetServices() {
				if svc.GetGateway() {
					g.P(name, "GRPCGateway *", grpc, ".GatewayOpts ", gen.Tag(name+" GRPC Gateway", server.GetName()+"-grpc-gateway"))
					break
				}
			}
		case *onyxpb.Server_Http_:
			g.P(name, "HTTP *", g.Qual(core+"/http", "Opts"), " ", gen.Tag(name+" HTTP (Server)", server.GetName()+"-http"))
		case *onyxpb.Server_GrpcWebProxy_:
			g.P(name, "GRPCWebProxy *", g.Qual(core+"/grpc/grpcwebproxy", "Opts"), " ", gen.Tag(name+" GRPC Web Proxy", server.GetName()+"-grpcwebproxy"))
		}
	}

	g.P()
	g.P("// Services.")
	for _, service := range g.b.Services {
		name := gen.Pascal(service.GetName())
		g.P(name, " *", g.ImportAs(service.Target.GoImportPath(g.b.GoImportPath), strings.ToLower(name)), ".Opts ", gen.Tag(name, service.GetName()))
	}
	g.P("}")
	g.P()
}

func (g *generator) grpcClients() {
	if len(g.b.GRPCClients) == 0 {
		return
	}
	grpc := g.Import(core + "/grpc")
	fmt_ := g.Import("fmt")
	g.P()
	g.P("// gRPC connections, one per endpoint.")
	g.P("endpointToGRPCConnection := map[string]*", grpc, ".Connection{}")
	g.P("connect := func(clientOpts *", grpc, ".ClientOpts) (*", grpc, ".Connection, error) {")
	g.P("if connection, ok := endpointToGRPCConnection[clientOpts.Endpoint()]; ok {")
	g.P("return connection, nil")
	g.P("}")
	g.P("connection, err := ", grpc, ".NewConnection(clientOpts, opts.Certs, opts.Prometheus)")
	g.P("if err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("if err := connection.Connect(ctx); err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("endpointToGRPCConnection[clientOpts.Endpoint()] = connection")
	g.P("return connection, nil")
	g.P("}")
	g.P("defer func() {")
	g.P("for _, connection := range endpointToGRPCConnection {")
	g.P("connection.Close()")
	g.P("}")
	g.P("}()")
	for _, client := range g.b.GRPCClients {
		clientOpts := g.grpcOptsField(client.Name)
		if client.Server != nil {
			clientOpts = serverOpts(client.Server, "GRPC") + ".ClientOpts()"
		}
		pb := gen.PB(g.File, client.GRPCService)
		connection := gen.Camel(client.Name) + "Connection"
		g.P()
		g.P(connection, ", err := connect(", clientOpts, ")")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("connecting to `, client.Name, `: %w", err)`)
		g.P("}")
		g.P(clientVar(client), " := ", pb, ".New", client.GoName, "Client(", connection, ".Get())")
		if client.HealthChecked {
			g.P(healthCheckVar(client), " := ", connection, ".HealthCheckFn(", pb, ".", client.GoName, "_ServiceDesc.ServiceName)")
		}
	}
}

func (g *generator) postgres() {
	if len(g.b.Databases) == 0 {
		return
	}
	postgres := g.Import(core + "/postgres")
	fmt_ := g.Import("fmt")
	g.P()
	g.P("// Postgres connections, one per endpoint.")
	g.P("endpointToPostgresClient := map[string]*", postgres, ".Client{}")
	g.P("connectPostgres := func(postgresOpts *", postgres, ".Opts) (*", postgres, ".Client, error) {")
	g.P("if client, ok := endpointToPostgresClient[postgresOpts.Endpoint()]; ok {")
	g.P("return client, nil")
	g.P("}")
	g.P("client := ", postgres, ".NewClient(postgresOpts)")
	g.P("if err := client.Start(ctx); err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("endpointToPostgresClient[postgresOpts.Endpoint()] = client")
	g.P("return client, nil")
	g.P("}")
	g.P("defer func() {")
	g.P("for _, client := range endpointToPostgresClient {")
	g.P("client.Close()")
	g.P("}")
	g.P("}()")
	for _, database := range g.b.Databases {
		g.P()
		g.P(psqlVar(database), ", err := connectPostgres(opts.", gen.Pascal(database.Name), "Postgres)")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("connecting to `, database.Name, ` database: %w", err)`)
		g.P("}")
	}
	if len(g.b.Stores) > 0 {
		g.P()
		for _, store := range g.b.Stores {
			g.P(storeVar(store), " := ", g.Qual(store.Target.GoImportPath(g.b.GoImportPath), "New"), "(", psqlVar(store.Database), ")")
		}
	}
}

func (g *generator) nats() {
	if !g.b.Nats {
		return
	}
	fmt_ := g.Import("fmt")
	g.P()
	g.P("natsClient, err := ", g.Qual(core+"/nats", "NewClient"), "(opts.Nats)")
	g.P("if err != nil {")
	g.P("return ", fmt_, `.Errorf("instantiating nats client: %w", err)`)
	g.P("}")
	g.P("if err := natsClient.Start(ctx); err != nil {")
	g.P("return ", fmt_, `.Errorf("starting nats client: %w", err)`)
	g.P("}")
	g.P("defer natsClient.Close()")
}

func (g *generator) components() {
	fmt_ := g.Import("fmt")
	for _, component := range g.b.Components {
		v := componentVar(component)
		g.P()
		g.P(v, ", err := ", g.Qual(component.Target.GoImportPath(g.b.GoImportPath), "New"), "(opts.", gen.Pascal(component.Name), "Service)")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("instantiating `, component.Name, ` service: %w", err)`)
		g.P("}")
		g.P(v, "Cleanup, err := ", v, ".Start(ctx, nil)")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("starting `, component.Name, ` service: %w", err)`)
		g.P("}")
		g.P("defer ", v, "Cleanup()")
	}
}

func (g *generator) interceptors() {
	fmt_ := g.Import("fmt")
	for _, i := range g.b.Interceptors {
		if !interceptors[i].opts {
			continue
		}
		name := interceptorName(i)
		args := "opts." + name + ", sessionManager"
		if interceptors[i].ctx {
			args = "ctx, " + args
		}
		g.P()
		g.P(gen.Camel(name), "Interceptor, err := ", g.Qual(core+"/authentication", "New"+name+"Interceptor"), "(", args, ")")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("instantiating `, gen.Human(name), ` interceptor: %w", err)`)
		g.P("}")
	}
}

func (g *generator) service(s *Service) {
	fmt_ := g.Import("fmt")
	v := serviceVar(s)
	withServiceAccount := "nil"
	if g.internalServiceAuthentication() {
		withServiceAccount = v + "WithServiceAccount"
		g.P(withServiceAccount, ", err := opts.InternalServiceAuthentication.WithServiceAccount(\"", s.GetName(), "\")")
		g.P("if err != nil {")
		g.P("return ", fmt_, `.Errorf("service account of `, s.GetName(), `: %w", err)`)
		g.P("}")
	}
	args := []string{serviceOpts(s)}
	for _, dep := range s.Dependencies {
		switch {
		case dep.GRPCClient != nil:
			args = append(args, clientVar(dep.GRPCClient))
		case dep.Store != nil:
			args = append(args, storeVar(dep.Store))
		case dep.Database != nil:
			args = append(args, psqlVar(dep.Database))
		case dep.Component != nil:
			args = append(args, componentVar(dep.Component))
		case dep.Nats:
			args = append(args, "natsClient")
		}
	}
	g.P(v, ", err := ", g.Qual(s.Target.GoImportPath(g.b.GoImportPath), "New"), "(", strings.Join(args, ", "), ")")
	g.P("if err != nil {")
	g.P("return ", fmt_, `.Errorf("instantiating `, s.GetName(), `: %w", err)`)
	g.P("}")
	g.P(v, "Cleanup, err := ", v, ".Start(ctx, ", withServiceAccount, ")")
	g.P("if err != nil {")
	g.P("return ", fmt_, `.Errorf("starting `, s.GetName(), `: %w", err)`)
	g.P("}")
	g.P("defer ", v, "Cleanup()")
}

// healthChecks are what a service's health on a server depends on: its databases and the gRPC
// services it dials, other than itself.
func (g *generator) healthChecks(s *Service) []string {
	var checks []string
	for _, dep := range s.Dependencies {
		switch {
		case dep.GRPCClient != nil && dep.GRPCClient.Service != s:
			checks = append(checks, healthCheckVar(dep.GRPCClient))
		case dep.Store != nil:
			checks = append(checks, psqlVar(dep.Store.Database)+".Ping")
		case dep.Database != nil:
			checks = append(checks, psqlVar(dep.Database)+".Ping")
		}
	}
	return checks
}

func (g *generator) grpcServer(s *Server) {
	grpc := g.Import(core + "/grpc")
	fmt_ := g.Import("fmt")
	v := serverVar(s, "GRPCServer")
	g.P(v, " := ", grpc, ".NewServer(", serverOpts(s, "GRPC"), ", opts.Certs, opts.Prometheus, \"", s.GetName(), "\", func(server *", grpc, ".Server) {")
	operations := map[*Service]bool{}
	for _, registration := range s.GRPC {
		g.P(gen.PB(g.File, registration.GRPC), ".Register", registration.GRPC.GoName, "Server(server.Raw, ", serviceVar(registration.Service), ")")
		if longrunning(registration.Service) && !operations[registration.Service] {
			operations[registration.Service] = true
			g.P("// AIP-151: a service returning Operations also serves google.longrunning.Operations.")
			g.P(g.Qual("cloud.google.com/go/longrunning/autogen/longrunningpb", "RegisterOperationsServer"), "(server.Raw, ", serviceVar(registration.Service), ")")
		}
	}
	g.P("})")
	if s.GetGrpc().GetDescriptorSet() != "" {
		g.P(v, ".WithFileDescriptorSet(", serverVar(s, "DescriptorSetBytes"), ")")
	}
	if len(s.GetGrpc().GetInterceptors()) > 0 {
		for _, kind := range []string{"Unary", "Stream"} {
			g.P(v, ".With", kind, "Interceptors(")
			for _, i := range s.GetGrpc().GetInterceptors() {
				if method := interceptors[i].method; method != "" {
					g.P("sessionManager.", kind, "Server", method, "Interceptor(),")
				} else {
					g.P(gen.Camel(interceptorName(i)), "Interceptor.", kind, "(),")
				}
			}
			g.P(")")
		}
	}
	g.P("gracefulStopFns = append(gracefulStopFns, ", v, ".GracefulStop)")
	g.P("stopFns = append(stopFns, ", v, ".Stop)")
	for _, registration := range s.GRPC {
		checks := append([]string{gen.PB(g.File, registration.GRPC) + "." + registration.GRPC.GoName + "_ServiceDesc.ServiceName"}, g.healthChecks(registration.Service)...)
		g.P(v, ".GetHealthServer().RegisterService(", strings.Join(checks, ", "), ")")
	}
	g.P("healthServer.RegisterService(\"", s.GetName(), "\", ", v, ".GetHealthServer().CheckFn())")
	g.P("// Bound now, so a dependent's Start() can reach it and a bad address fails here.")
	g.P("if err := ", v, ".Listen(ctx); err != nil {")
	g.P("return ", fmt_, `.Errorf("listening `, s.GetName(), `: %w", err)`)
	g.P("}")
	g.P("runServer(ctx, \"", s.GetName(), "\", ", v, ".Serve)")

	var handlers []string
	for _, registration := range s.GRPC {
		if registration.GetGateway() {
			handlers = append(handlers, gen.PB(g.File, registration.GRPC)+".Register"+registration.GRPC.GoName+"HandlerFromEndpoint")
		}
	}
	if len(handlers) > 0 {
		gateway := serverVar(s, "GRPCGateway")
		g.P(gateway, " := ", grpc, ".NewGateway(", serverOpts(s, "GRPCGateway"), ", ", serverOpts(s, "GRPC"), ".ClientOpts(), opts.Certs, opts.Prometheus, []", grpc, ".RegisterHandler{")
		for _, handler := range handlers {
			g.P(handler, ",")
		}
		g.P("})")
		g.P("gracefulStopFns = append(gracefulStopFns, ", gateway, ".GracefulStop)")
		g.P("stopFns = append(stopFns, ", gateway, ".Stop)")
		g.P("runServer(ctx, \"", s.GetName(), " gateway\", ", gateway, ".Serve)")
	}
}

func (g *generator) httpServer(s *Server) {
	http := g.Import(core + "/http")
	v := serverVar(s, "HTTPServer")
	g.P(v, " := ", http, ".NewServer(", serverOpts(s, "HTTP"), ", \"", s.GetName(), "\", func(server *", http, ".Server) {")
	for _, service := range s.Services {
		g.P(serviceVar(service), ".RegisterRoutes(server)")
	}
	g.P("})")
	g.P("gracefulStopFns = append(gracefulStopFns, ", v, ".GracefulStop)")
	g.P("stopFns = append(stopFns, ", v, ".Stop)")
	for _, service := range s.Services {
		checks := append([]string{"\"" + service.GetName() + "\""}, g.healthChecks(service)...)
		g.P(v, ".GetHealthServer().RegisterService(", strings.Join(checks, ", "), ")")
	}
	g.P("healthServer.RegisterService(\"", s.GetName(), "\", ", v, ".GetHealthServer().CheckFn())")
	g.P("runServer(ctx, \"", s.GetName(), "\", ", v, ".Serve)")
}

func (g *generator) grpcWebProxy(s *Server) {
	v := serverVar(s, "GRPCWebProxy")
	g.P(v, " := ", g.Qual(core+"/grpc/grpcwebproxy", "NewServer"), "(", serverOpts(s, "GRPCWebProxy"), ", opts.Certs, opts.Prometheus)")
	g.P("gracefulStopFns = append(gracefulStopFns, ", v, ".GracefulStop)")
	g.P("stopFns = append(stopFns, ", v, ".Stop)")
	g.P("healthServer.RegisterService(\"", s.GetName(), "\", ", v, ".HealthCheckFn())")
	g.P("runServer(ctx, \"", s.GetName(), "\", ", v, ".Serve)")
}

func (g *generator) handleSignals() {
	ctx := g.Import("context")
	slog := g.Import("log/slog")
	g.P("func handleSignals(ctx ", ctx, ".Context, errChan chan error, gracefulStopFns, stopFns []func() error) {")
	g.P("signalChan := make(chan ", g.Qual("os", "Signal"), ", 2) // One for each category of stops.")
	g.P(g.Qual("os/signal", "Notify"), "(signalChan, ", g.Qual("syscall", "SIGTERM"), ", ", g.Qual("syscall", "SIGINT"), ", ", g.Qual("syscall", "SIGHUP"), ")")
	g.P()
	g.P(slog, `.InfoContext(ctx, "waiting for signal")`)
	g.P("select {")
	g.P("case sig := <-signalChan:")
	g.P(slog, `.InfoContext(ctx, "received signal #1: initiating graceful shutdown", "signal", sig)`)
	g.P("case err := <-errChan:")
	g.P(slog, `.ErrorContext(ctx, "server failed", "error", err)`)
	g.P("}")
	g.P()
	g.P("// Graceful stops run in reverse start order; a second signal forces the stop.")
	g.P("gracefulDone := make(chan struct{})")
	g.P("go func() {")
	g.P("for i := len(gracefulStopFns) - 1; i >= 0; i-- {")
	g.P("gracefulStopFns[i]()")
	g.P("}")
	g.P("close(gracefulDone)")
	g.P("}()")
	g.P("select {")
	g.P("case <-gracefulDone:")
	g.P(slog, `.InfoContext(ctx, "graceful shutdown completed")`)
	g.P("case sig := <-signalChan:")
	g.P(slog, `.WarnContext(ctx, "received signal #2: initiating force shutdown", "signal", sig)`)
	g.P("for i := len(stopFns) - 1; i >= 0; i-- {")
	g.P("stopFns[i]()")
	g.P("}")
	g.P(slog, `.InfoContext(ctx, "force shutdown completed")`)
	g.P("}")
	g.P("}")
}
