// Package mock generates a typed recorder per gRPC service, wrapping the untyped recorder of
// go/grpc/mock_server so that a test names an endpoint through the compiler rather than through
// a fully-qualified method name, and passes it the request and response types it was declared
// with.
package mock

import (
	"google.golang.org/protobuf/compiler/protogen"

	"github.com/malonaz/core/tools/protoc-gen-core/plugin"
)

const (
	contextPkg    = protogen.GoImportPath("context")
	mockServerPkg = protogen.GoImportPath("github.com/malonaz/core/go/grpc/mock_server")
)

// Generate emits a mock for every service in the file. Files declaring no service generate
// nothing, as do the streaming endpoints of a service that has both, which the mock gRPC server
// does not serve.
func Generate(file *protogen.File, g *protogen.GeneratedFile, packageName protogen.GoPackageName, opts *plugin.Opts) error {
	if len(file.Services) == 0 {
		g.Skip()
		return nil
	}

	g.P("// Code generated by protoc-gen-api. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P("package ", packageName)
	g.P()

	ident := func(path protogen.GoImportPath, name string) string {
		return g.QualifiedGoIdent(protogen.GoIdent{GoName: name, GoImportPath: path})
	}

	for _, service := range file.Services {
		generateService(g, ident, file.GoImportPath, service)
	}
	return nil
}

type identFunc func(path protogen.GoImportPath, name string) string

// generateService emits the handle a test declares expectations through, and one expectation
// type per unary endpoint.
func generateService(
	g *protogen.GeneratedFile, ident identFunc,
	pbImportPath protogen.GoImportPath, service *protogen.Service,
) {
	mockName := service.GoName + "Mock"
	recorderName := mockName + "Recorder"
	serviceFQN := string(service.Desc.FullName())

	g.P("// ", mockName, " declares expectations on a mock gRPC server standing in for ", serviceFQN, ".")
	g.P("type ", mockName, " struct {")
	g.P("recorder *", ident(mockServerPkg, "Recorder"))
	g.P("}")
	g.P()
	g.P("// New", mockName, " returns a handle for declaring ", serviceFQN, " expectations on server.")
	g.P("// Several services can be mocked on one server, each through its own handle.")
	g.P("func New", mockName, "(server *", ident(mockServerPkg, "Server"), ") *", mockName, " {")
	g.P("return &", mockName, "{recorder: server.EXPECT()}")
	g.P("}")
	g.P()
	g.P("// EXPECT returns a recorder for declaring expectations.")
	g.P("func (m *", mockName, ") EXPECT() *", recorderName, " {")
	g.P("return (*", recorderName, ")(m)")
	g.P("}")
	g.P()
	g.P("// ", recorderName, " declares expectations on ", mockName, ".")
	g.P("type ", recorderName, " ", mockName)
	g.P()

	for _, method := range service.Methods {
		if streaming := streamingKind(method); streaming != "" {
			g.P("// ", method.GoName, " is a ", streaming, " endpoint, which the mock gRPC server does not")
			g.P("// serve, so no expectation can be declared on it.")
			g.P()
			continue
		}
		generateUnaryMethod(g, ident, pbImportPath, service, method, recorderName)
	}
}

// generateUnaryMethod emits the expectation type for one unary endpoint. Its options mirror
// those of mock_server.UnaryCall, typed to the endpoint and returning the expectation so that
// they stay chainable.
func generateUnaryMethod(
	g *protogen.GeneratedFile, ident identFunc, pbImportPath protogen.GoImportPath,
	service *protogen.Service, method *protogen.Method, recorderName string,
) {
	callName := service.GoName + method.GoName + "Call"
	methodFQN := string(service.Desc.FullName()) + "/" + string(method.Desc.Name())
	// The full method name comes from the generated gRPC stub rather than from a string built
	// here, so a proto package that is not generating gRPC code fails to compile its mock
	// instead of standing in for an endpoint nothing serves.
	fullMethodName := ident(pbImportPath, service.GoName+"_"+method.GoName+"_FullMethodName")
	requestType := "*" + g.QualifiedGoIdent(method.Input.GoIdent)
	responseType := "*" + g.QualifiedGoIdent(method.Output.GoIdent)

	g.P("// ", method.GoName, " declares an expectation on ", methodFQN, ".")
	g.P("func (r *", recorderName, ") ", method.GoName, "() *", callName, " {")
	g.P("return &", callName, "{unaryCall: r.recorder.Unary(", fullMethodName, ")}")
	g.P("}")
	g.P()
	g.P("// ", callName, " is an expectation on ", methodFQN, ".")
	g.P("type ", callName, " struct {")
	g.P("unaryCall *", ident(mockServerPkg, "UnaryCall"))
	g.P("}")
	g.P()

	g.P("// WithPayload restricts the expectation to requests equal to payload. Without it, any")
	g.P("// request to the endpoint matches.")
	g.P("func (c *", callName, ") WithPayload(payload ", requestType, ") *", callName, " {")
	g.P("c.unaryCall.WithPayload(payload)")
	g.P("return c")
	g.P("}")
	g.P()

	g.P("// Return sets the message to reply with. Without it, the endpoint's zero-value response")
	g.P("// message is returned.")
	g.P("func (c *", callName, ") Return(response ", responseType, ") *", callName, " {")
	g.P("c.unaryCall.Return(response)")
	g.P("return c")
	g.P("}")
	g.P()

	g.P("// ReturnError sets the error to fail with. Pass a status error to control the code the")
	g.P("// caller sees; anything else surfaces as codes.Unknown, as it would from a real server.")
	g.P("func (c *", callName, ") ReturnError(err error) *", callName, " {")
	g.P("c.unaryCall.ReturnError(err)")
	g.P("return c")
	g.P("}")
	g.P()

	g.P("// Handle computes the reply from the request, for an endpoint whose response depends on")
	g.P("// what it was called with. It takes precedence over Return and ReturnError.")
	g.P("func (c *", callName, ") Handle(")
	g.P("handler func(", ident(contextPkg, "Context"), ", ", requestType, ") (", responseType, ", error),")
	g.P(") *", callName, " {")
	g.P(ident(mockServerPkg, "Handle"), "(c.unaryCall, handler)")
	g.P("return c")
	g.P("}")
	g.P()

	g.P("// Times requires the expectation to be matched exactly count times.")
	g.P("func (c *", callName, ") Times(count int) *", callName, " {")
	g.P("c.unaryCall.Times(count)")
	g.P("return c")
	g.P("}")
	g.P()

	g.P("// AnyTimes lets the expectation match any number of times, including none. Use it for")
	g.P("// endpoints a dependency calls on its own schedule, which no test asserts on.")
	g.P("func (c *", callName, ") AnyTimes() *", callName, " {")
	g.P("c.unaryCall.AnyTimes()")
	g.P("return c")
	g.P("}")
	g.P()
}

// streamingKind names how a method streams, or returns an empty string for a unary one.
func streamingKind(method *protogen.Method) string {
	switch {
	case method.Desc.IsStreamingClient() && method.Desc.IsStreamingServer():
		return "bidirectional-streaming"
	case method.Desc.IsStreamingClient():
		return "client-streaming"
	case method.Desc.IsStreamingServer():
		return "server-streaming"
	}
	return ""
}
