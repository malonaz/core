// Package aip generates a file's AIP companions: typed resource names for every
// declared resource, plus the Labels and Annotations sets the package declares.
package aip

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoregistry"

	"github.com/malonaz/core/tools/protoc-gen-core/plugin"
)

const (
	aipPkg          = protogen.GoImportPath("github.com/malonaz/core/go/aip")
	resourcenamePkg = protogen.GoImportPath("go.einride.tech/aip/resourcename")
)

// Generate emits `{file}_aip.pb.go`, or skips the file when it declares nothing.
func Generate(file *protogen.File, g *protogen.GeneratedFile, packageName protogen.GoPackageName, opts *plugin.Opts) error {
	files, err := registry(opts)
	if err != nil {
		return err
	}
	g.P("// Code generated by protoc-gen-core. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", packageName)

	var generated bool
	for _, generate := range []func() (bool, error){
		func() (bool, error) { return generateResourceNames(file, g, files) },
		func() (bool, error) { return generateLabels(file, g) },
		func() (bool, error) { return generateAnnotations(file, g, opts) },
	} {
		ok, err := generate()
		if err != nil {
			return fmt.Errorf("%s: %w", file.Desc.Path(), err)
		}
		generated = generated || ok
	}
	if !generated {
		g.Skip()
	}
	return nil
}

var filesRegistry *protoregistry.Files

// registry indexes the whole compilation unit once; parent lookups span files.
func registry(opts *plugin.Opts) (*protoregistry.Files, error) {
	if filesRegistry != nil {
		return filesRegistry, nil
	}
	files := new(protoregistry.Files)
	for _, file := range opts.Files {
		if err := files.RegisterFile(file.Desc); err != nil {
			return nil, fmt.Errorf("registering %s: %w", file.Desc.Path(), err)
		}
	}
	filesRegistry = files
	return files, nil
}
